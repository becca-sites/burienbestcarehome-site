// Converts the weekly blog markdown files in /blog into
// src/content/posts-weekly.ts so they show up on the live site.
//
// Usage (from nextjs-site/):  node scripts/build-weekly-posts.mjs
//
// Only files with `publish: true` in their front matter are included.
// The post's `date` decides where it sorts on /blog, so a post can be
// backdated (or future-dated) just by editing that line.
//
// Markdown supported in the body: ## and ### headings, paragraphs,
// "- " bullet lists, "> " quotes, plus **bold**, *italic* and [links](/x).
// A "## Frequently Asked Questions" section made of "### Question" +
// answer paragraph pairs also becomes FAQPage structured data.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const blogDir = path.resolve(here, '../../blog')
const outFile = path.resolve(here, '../src/content/posts-weekly.ts')

function parseFrontMatter(src) {
  const m = src.match(/^---\n([\s\S]*?)\n---\n?/)
  if (!m) return { data: {}, body: src }
  const data = {}
  let key = null
  for (const line of m[1].split('\n')) {
    const list = line.match(/^\s+-\s+(.*)$/)
    if (list && key) {
      if (!Array.isArray(data[key])) data[key] = []
      data[key].push(unquote(list[1]))
      continue
    }
    const kv = line.match(/^([A-Za-z_]+):\s*(.*)$/)
    if (kv) {
      key = kv[1]
      data[key] = kv[2] === '' ? [] : unquote(kv[2])
    }
  }
  return { data, body: src.slice(m[0].length) }
}

function unquote(s) {
  s = s.trim()
  if ((s.startsWith('"') && s.endsWith('"')) || (s.startsWith("'") && s.endsWith("'"))) {
    return s.slice(1, -1)
  }
  return s
}

function plain(text) {
  return text
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
    .replace(/\*\*([^*]+)\*\*/g, '$1')
    .replace(/\*([^*]+)\*/g, '$1')
}

function toBlocks(body) {
  const blocks = []
  const chunks = body.replace(/\r/g, '').split(/\n\s*\n/)
  for (const raw of chunks) {
    const chunk = raw.trim()
    if (!chunk) continue
    if (chunk.startsWith('# ')) continue // title is rendered by the page
    if (chunk.startsWith('### ')) {
      blocks.push({ type: 'h3', text: chunk.slice(4).trim() })
      continue
    }
    if (chunk.startsWith('## ')) {
      blocks.push({ type: 'h2', text: chunk.slice(3).trim() })
      continue
    }
    const lines = chunk.split('\n')
    if (lines.every((l) => /^\s*[-*]\s+/.test(l))) {
      blocks.push({ type: 'ul', items: lines.map((l) => l.replace(/^\s*[-*]\s+/, '').trim()) })
      continue
    }
    if (lines.every((l) => l.startsWith('>'))) {
      blocks.push({ type: 'quote', text: lines.map((l) => l.replace(/^>\s?/, '')).join(' ').trim() })
      continue
    }
    blocks.push({ type: 'p', text: lines.join(' ').trim() })
  }
  return blocks
}

function faqFrom(blocks) {
  const start = blocks.findIndex((b) => b.type === 'h2' && /frequently asked/i.test(b.text))
  if (start < 0) return undefined
  const mainEntity = []
  for (let i = start + 1; i < blocks.length; i++) {
    const b = blocks[i]
    if (b.type === 'h2') break
    if (b.type === 'h3' && blocks[i + 1]?.type === 'p') {
      mainEntity.push({
        '@type': 'Question',
        name: plain(b.text),
        acceptedAnswer: { '@type': 'Answer', text: plain(blocks[i + 1].text) },
      })
    }
  }
  if (!mainEntity.length) return undefined
  return { '@context': 'https://schema.org', '@type': 'FAQPage', mainEntity }
}

const files = fs
  .readdirSync(blogDir)
  .filter((f) => f.endsWith('.md'))
  .sort()

const posts = []
for (const f of files) {
  const { data, body } = parseFrontMatter(fs.readFileSync(path.join(blogDir, f), 'utf8'))
  if (String(data.publish) !== 'true') continue
  for (const req of ['title', 'slug', 'date', 'description']) {
    if (!data[req]) throw new Error(`${f}: missing "${req}" in front matter`)
  }
  if (/—/.test(body) || /—/.test(data.title + data.description)) {
    throw new Error(`${f}: contains an em dash, which the content rules forbid`)
  }
  const blocks = toBlocks(body)
  const words = plain(body).split(/\s+/).filter(Boolean).length
  const post = {
    slug: data.slug,
    title: data.title,
    description: data.description,
    date: data.date,
    author: data.author || 'Becca Pitts',
    readingTime: `${Math.max(1, Math.round(words / 230))} min`,
    tags: Array.isArray(data.tags) ? data.tags : [],
  }
  if (data.heroImage) post.heroImage = data.heroImage
  const faq = faqFrom(blocks)
  if (faq) post.faqSchema = faq
  post.body = blocks
  posts.push(post)
}

const out = `// GENERATED by scripts/build-weekly-posts.mjs from the blog/ markdown files
// that have \`publish: true\`. Edit the markdown and re-run the script rather
// than hand-editing this file.

import type { Post } from './posts'

export const weeklyPosts: Post[] = ${JSON.stringify(posts, null, 2)}
`
fs.writeFileSync(outFile, out)
console.log(`Wrote ${posts.length} post(s) to ${path.relative(process.cwd(), outFile)}`)
for (const p of posts) console.log(`  ${p.date}  /blog/${p.slug}  (${p.readingTime})`)
